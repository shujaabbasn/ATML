#---------------- helpers ----------------

def read_csv(name):
    """Rows of outputs/tables/<name>.csv as dicts (written earlier in the same make_report_assets run)."""
    rows=[]
    with open(TABLES/f"{name}.csv") as f:
        for row in csv.DictReader(f):
            rows.append(row)
    return rows


def read_lists(name):
    """Rows as plain lists, for the csv files that repeat a column name (low/high, Wilcoxon p)."""
    rows=[]
    with open(TABLES/f"{name}.csv") as f:
        reader=csv.reader(f)
        next(reader) #skip the header
        for row in reader:
            rows.append(row)
    return rows


def number(value,digits):
    """Fixed decimals, '--' for an empty cell."""
    if value is None or value=="":
        return "--"
    return f"{float(value):.{digits}f}"


def signed(value,digits):
    """+1.2 or $-$1.2 (latex minus), so a change reads as a change."""
    if value is None or value=="":
        return "--"
    v=float(value)
    text=f"{abs(v):.{digits}f}"
    if float(text)==0.0:
        return text
    if v>0:
        return "+"+text
    else:
        return "$-$"+text


def ppl(value):
    """Perplexity: 2 decimals below 1,000, otherwise a power of ten so the column stays narrow."""
    v=float(value)
    if abs(v)<1000:
        return f"{v:.2f}"
    exponent=0
    mantissa=abs(v)
    while mantissa>=10:
        mantissa=mantissa/10
        exponent=exponent+1
    sign=""
    if v<0:
        sign="$-$"
    return f"{sign}${mantissa:.2f}\\times10^{{{exponent}}}$"


def signed_ppl(value):
    v=float(value)
    if abs(v)<1000:
        return signed(v,2)
    if v>0:
        return "+"+ppl(v)
    else:
        return ppl(v)


def span(values,digits):
    """min-max of a list as 'a--b', one value if they are all equal at this rounding, '--' if empty."""
    if len(values)==0:
        return "--"
    low=number(min(values),digits)
    high=number(max(values),digits)
    if low==high:
        return low
    return low+"--"+high


def interval(mean,low,high,digits,scale=1.0):
    return f"{signed(scale*float(mean),digits)} [{signed(scale*float(low),digits)}, {signed(scale*float(high),digits)}]"


def tex(text):
    return str(text).replace("_","\\_").replace("%","\\%").replace("&","\\&").replace("#","\\#")


def write_full(name,caption,label,header,rows,columns,size="scriptsize"):
    """One table environment per file. Rows hold finished latex strings."""
    FULL.mkdir(parents=True,exist_ok=True)
    lines=[]
    lines.append("% generated by report_tables.py (make_report_assets.py) from the results files")
    lines.append("\\begin{table}[!htb]")
    lines.append("\\centering")
    lines.append("\\"+size)
    lines.append("\\setlength{\\tabcolsep}{3.5pt}")
    lines.append("\\caption{"+caption+"}")
    lines.append("\\label{"+label+"}")
    lines.append("\\begin{adjustbox}{max width=\\linewidth}") #shrink only when wider than the line or minipage
    lines.append("\\begin{tabular}{"+columns+"}")
    lines.append("\\toprule")
    lines.append(" & ".join(header)+" \\\\")
    lines.append("\\midrule")
    for row in rows:
        if row=="midrule":
            lines.append("\\midrule")
        else:
            lines.append(" & ".join(row)+" \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{adjustbox}")
    lines.append("\\end{table}")
    (FULL/f"{name}.tex").write_text("\n".join(lines)+"\n")
    #same table without the float, for two tables side by side in one minipage pair (needs \\usepackage{capt-of})
    inner=[]
    for line in lines[3:-1]:
        if line.startswith("\\caption{"):
            inner.append("\\captionof{table}{"+line[len("\\caption{"):])
        else:
            inner.append(line)
    (FULL/f"{name}_inner.tex").write_text("\n".join(inner)+"\n")
    print("report table",name,len(rows),"rows")


