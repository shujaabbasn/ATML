def t1_name(condition):
    names={"baseline_fp16":"FP16 (unchanged)","nm24_wanda_s50":"2:4 Wanda 50\\%"}
    if condition in names:
        return names[condition]
    parts=condition.split("_")
    if condition.startswith("p1"):
        return f"P1 magnitude {parts[2][1:]}\\%"
    if condition.startswith("p2"):
        return f"P2 Wanda {parts[2][1:]}\\%"
    if condition.startswith("p3"):
        return f"P3 OWL {parts[2][1:]}\\%"
    if condition.startswith("q1"):
        return f"Q1 RTN {parts[2].upper()}"
    if condition.startswith("q2"):
        return f"Q2 AWQ {parts[2].upper()}"
    if condition.startswith("q3"):
        return f"Q3 mixed (= Q2 {parts[3].upper()} bytes)"
    return tex(condition)


def t3_name(condition):
    """spec_on_policy_s6304_g4 -> On s6304, gamma 4."""
    text=condition.replace("spec_","")
    gamma=""
    if "_g" in text:
        gamma=text.split("_g")[-1]
        text=text[:text.rfind("_g")]
    text=text.replace("student_only_","")
    names={"original":"Original","target_only":"Target only"}
    if text in names:
        label=names[text]
    elif text.startswith("off_policy"):
        label="Off "+text.split("_")[-1]
    elif text.startswith("on_policy"):
        label="On "+text.split("_")[-1]
    else:
        label=tex(text)
    if gamma!="":
        label=label+f", $\\gamma$={gamma}"
    return label


