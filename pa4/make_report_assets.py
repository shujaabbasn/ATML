#---------------- helpers ----------------

def fmt(value,digits):
    if value is None:
        return "--"
    if isinstance(value,str):
        return value
    if isinstance(value,bool):
        return str(value)
    if isinstance(value,(int,np.integer)):
        return str(int(value))
    if np.isnan(value):
        return "--"
    return f"{value:.{digits}f}"


def write_table(name,header,rows,digits=3,caption=""):
    """Same rows to <name>.csv (full precision) and <name>.tex (booktabs, rounded)."""
    TABLES.mkdir(parents=True,exist_ok=True)
    with open(TABLES/f"{name}.csv","w",newline="") as f:
        writer=csv.writer(f)
        writer.writerow(header)
        for row in rows:
            writer.writerow(row)
    lines=[]
    lines.append("% generated by make_report_assets.py from the results files")
    lines.append("\\begin{tabular}{"+"l"*1+"r"*(len(header)-1)+"}")
    lines.append("\\toprule")
    lines.append(" & ".join(escape_all(header))+" \\\\")
    lines.append("\\midrule")
    for row in rows:
        cells=[]
        for value in row:
            cells.append(escape(fmt(value,digits)))
        lines.append(" & ".join(cells)+" \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    if caption!="":
        lines.append("% "+caption)
    (TABLES/f"{name}.tex").write_text("\n".join(lines)+"\n")
    print("table",name,len(rows),"rows")


def escape(text):
    return str(text).replace("_","\\_").replace("%","\\%").replace("&","\\&").replace("#","\\#")


def escape_all(items):
    out=[]
    for item in items:
        out.append(escape(item))
    return out


def save_figure(figure,name):
    FIGURES.mkdir(parents=True,exist_ok=True)
    figure.tight_layout()
    figure.savefig(FIGURES/f"{name}.pdf")
    plt.close(figure)
    print("figure",name)


def metric_folders(root):
    out=[]
    for folder in sorted(root.iterdir()):
        if folder.is_dir() and (folder/"metrics.json").exists():
            out.append(folder)
    return out


