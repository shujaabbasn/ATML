def mean_field(rows,key):
    values=[]
    for row in rows:
        if key in row:
            values.append(row[key]["mean_ms"])
    if len(values)==0:
        return None
    return float(np.mean(values))


def mean_plain(rows,key):
    values=[]
    for row in rows:
        values.append(row[key])
    return float(np.mean(values))


